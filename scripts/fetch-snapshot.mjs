#!/usr/bin/env node
// Build-time data freshness: fetch the SAME live APIs the calculators'
// client scripts use (open.er-api.com FX, Coinbase crypto spot,
// api.gold-api.com gold) and regenerate src/data/fx-snapshot.ts + the
// TICKER_STATIC block in src/data/site.ts. Wired as the FIRST step of
// `npm run build`, so every deployed page carries numbers that were true
// the moment it was built — the ticker and the calculators share this one
// source and can never disagree again.
//
// Honest degradation: any fetch failure leaves the previous files untouched
// (their as_of stamps stay truthful) and the build proceeds; the client-side
// ticker-live.js port still refreshes visitors' values live.
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const get = async (url) => {
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), 8000);
  try {
    const r = await fetch(url, { cache: "no-cache", signal: ctrl.signal });
    if (!r.ok) throw new Error(`HTTP ${r.status}`);
    return await r.json();
  } finally { clearTimeout(t); }
};

let ok = 0, fail = 0;
const fx = await get("https://open.er-api.com/v6/latest/USD")
  .then((d) => (d.result === "success" ? (ok++, d) : (fail++, null)))
  .catch(() => (fail++, null));
const btc = await get("https://api.coinbase.com/v2/prices/BTC-USD/spot")
  .then((d) => (d?.data?.amount ? (ok++, d.data.amount) : (fail++, null)))
  .catch(() => (fail++, null));
const eth = await get("https://api.coinbase.com/v2/prices/ETH-USD/spot")
  .then((d) => (d?.data?.amount ? (ok++, d.data.amount) : (fail++, null)))
  .catch(() => (fail++, null));
const gold = await get("https://api.gold-api.com/price/XAU")
  .then((d) => (d?.price > 0 ? (ok++, d.price) : (fail++, null)))
  .catch(() => (fail++, null));

if (!fx) { console.log(`snapshot-fetch: er-api FAILED (${fail} errors) — keeping previous snapshot, build proceeds`); process.exit(0); }

const CUR = ["USD", "NGN", "GBP", "EUR", "CAD", "AED", "SAR", "GHS", "XOF", "XAF", "CNY", "JPY", "INR", "KES", "EGP", "ZAR"];
const rates = {};
for (const c of CUR) rates[c] = fx.rates[c];

// er-api stamps time_last_update_utc ("Wed, 30 Sep 2026 00:02:31 +0000");
// pages print the same moment in the site's house date format.
const stamp = new Date(fx.time_last_update_utc);
const iso = Number.isNaN(stamp.getTime()) ? new Date() : stamp;
const asOf = iso.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" })
  + ", " + String(iso.getUTCHours()).padStart(2, "0") + ":" + String(iso.getUTCMinutes()).padStart(2, "0") + " UTC";

const snapPath = path.join(root, "src/data/fx-snapshot.ts");
writeFileSync(snapPath, `// GENERATED by scripts/fetch-snapshot.mjs at build time — do not hand-edit.
// Fetched ${asOf} from open.er-api.com (the exact feed the converter's client
// script refreshes from), Coinbase spot + gold-api for the ticker pairs.
// The static render is this snapshot; browser scripts swap it for live values
// within ~1s (8s timeout; on failure the snapshot below stands, honestly
// stamped).
export interface FxSnapshot {
  ok: boolean;
  rates: Record<string, number>;
  as_of: string;
  cached: boolean;
}

export const FX_SNAPSHOT: FxSnapshot = {
  ok: true,
  rates: ${JSON.stringify(Object.fromEntries(CUR.map((c) => [c, rates[c]])), null, 2).replace(/\n/g, "\n  ")},
  as_of: "${asOf}",
  cached: ${fx.time_last_update_cached === true ? "true" : "false"},
};

export const FX_SNAPSHOT_LABEL = "live at build — refreshes in your browser";

// Unix seconds of the feed's own stamp; ticker-live.js skips the network
// only within 60s of it (a static build is always older, so visitors get a
// live refresh while crawlers see the truthful build-time figures).
export const FX_SNAPSHOT_TS = ${Math.floor(iso.getTime() / 1000)};
`);

// ── ticker strip: SAME numbers, formatted like the theme's PHP ticker ──
const fmt = (n, sym) => sym + Math.round(n).toLocaleString("en-US");
const r = fx.rates;
const pairs = [
  ["USD/NGN", "fx", fmt(r.NGN, "₦")],
  ["GBP/NGN", "fx", fmt(r.NGN / r.GBP, "₦")],
  ["EUR/NGN", "fx", fmt(r.NGN / r.EUR, "₦")],
  ["BTC/USD", "btc", btc ? fmt(btc, "$") : null],
  ["ETH/USD", "eth", eth ? fmt(eth, "$") : null],
  ["XAU/USD", "gold", gold ? fmt(gold, "$") : null],
];
const sitePath = path.join(root, "src/data/site.ts");
let site = readFileSync(sitePath, "utf8");
const prevBlock = site.slice(site.indexOf("export const TICKER_STATIC = ["), site.indexOf("];", site.indexOf("export const TICKER_STATIC")) + 2);
// crypto/gold failed → keep the previous value for that row (never " - " —
// this port renders a stamped snapshot server-side, not WP's dash).
const prevOf = (label) => (prevBlock.match(new RegExp(`label: "${label}", value: "([^"]*)"`)) || [])[1];
const lines = pairs.map(([label, src, value]) =>
  `  { label: "${label}", value: "${value || prevOf(label)}", src: "${src}" },`);
const block = `export const TICKER_STATIC = [\n${lines.join("\n")}\n];`;
site = site.replace(prevBlock, block);
site = site.replace(/\/\/ Static ticker snapshot[^\n]*\n(\/\/[^\n]*\n)*/,
  `// TICKER_STATIC is REWRITTEN at build time by scripts/fetch-snapshot.mjs\n// from the same feeds the calculators use — label = data-pair, value =\n// the rendered .t-rate. data-src lets the ported ticker-live.js refresh\n// pairs per source. Never hand-edit the values; they are generated.\n`);
writeFileSync(sitePath, site);

console.log(`snapshot-fetch: er-api ${ok}/4 sources ok${fail ? ` (${fail} failed — previous value kept)` : ""} → FX as_of ${asOf}, USD/NGN ${fmt(r.NGN, "₦")}, BTC ${btc ? fmt(btc, "$") : "kept"}, ETH ${eth ? fmt(eth, "$") : "kept"}, XAU ${gold ? fmt(gold, "$") : "kept"}`);
